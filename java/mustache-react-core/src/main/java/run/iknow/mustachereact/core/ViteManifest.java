package run.iknow.mustachereact.core;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * The {@code .vite/manifest.json} written by {@code vite build}.
 *
 * <p>Used to find the hashed file names of the client entry and of the page being rendered, so that the HTML can
 * reference them directly and preload the page chunk instead of waiting for the entry to request it.
 */
public final class ViteManifest {

    /** Name of the client entry chunk generated by {@code @mustache-react/vite-plugin}. */
    public static final String ENTRY_NAME = "mustache-react";

    private static final String[] COMPONENT_EXTENSIONS = {".tsx", ".jsx", ".ts", ".js"};

    private final Map<String, Chunk> chunks;

    private ViteManifest(Map<String, Chunk> chunks) {
        this.chunks = chunks;
    }

    /**
     * Reads a manifest.
     *
     * @param in the manifest content, UTF-8; closed by this method
     * @return the parsed manifest
     * @throws IOException if reading fails
     * @throws IllegalArgumentException if the content is not a Vite manifest
     */
    public static ViteManifest read(InputStream in) throws IOException {
        try (InputStream input = in) {
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            byte[] buffer = new byte[8192];
            int n;
            while ((n = input.read(buffer)) != -1) {
                out.write(buffer, 0, n);
            }
            return parse(new String(out.toByteArray(), StandardCharsets.UTF_8));
        }
    }

    /**
     * Parses a manifest.
     *
     * @param json the manifest content
     * @return the parsed manifest
     * @throws IllegalArgumentException if the content is not a Vite manifest
     */
    public static ViteManifest parse(String json) {
        Object root = JsonParser.parse(json);
        if (!(root instanceof Map)) {
            throw new IllegalArgumentException("A Vite manifest must be a JSON object");
        }
        Map<String, Chunk> chunks = new LinkedHashMap<>();
        for (Map.Entry<?, ?> entry : ((Map<?, ?>) root).entrySet()) {
            if (entry.getValue() instanceof Map) {
                chunks.put(String.valueOf(entry.getKey()), new Chunk((Map<?, ?>) entry.getValue()));
            }
        }
        return new ViteManifest(chunks);
    }

    /**
     * Collects the assets for a page: the client entry, plus the chunk of the given component when it is in the
     * manifest.
     *
     * @param component component path relative to the frontend directory without extension,
     *        e.g. {@code pages/orders/OrderList}; {@code null} for the entry only
     * @return the assets to reference from the HTML
     * @throws IllegalStateException if the manifest has no mustache-react entry
     */
    public PageAssets assetsFor(String component) {
        String entryKey = findEntryKey();
        Chunk entry = chunks.get(entryKey);

        Set<String> styles = new LinkedHashSet<>();
        Set<String> preloads = new LinkedHashSet<>();
        Set<String> visited = new LinkedHashSet<>();
        visited.add(entryKey);
        styles.addAll(entry.css);
        collectImports(entry, styles, preloads, visited);

        String componentKey = component == null ? null : findComponentKey(component);
        if (componentKey != null && visited.add(componentKey)) {
            Chunk chunk = chunks.get(componentKey);
            preloads.add(chunk.file);
            styles.addAll(chunk.css);
            collectImports(chunk, styles, preloads, visited);
        }
        return new PageAssets(
                new ArrayList<>(Collections.singletonList(entry.file)),
                new ArrayList<>(styles),
                new ArrayList<>(preloads));
    }

    private void collectImports(Chunk chunk, Set<String> styles, Set<String> preloads, Set<String> visited) {
        for (String key : chunk.imports) {
            if (!visited.add(key)) {
                continue;
            }
            Chunk imported = chunks.get(key);
            if (imported == null) {
                continue;
            }
            preloads.add(imported.file);
            styles.addAll(imported.css);
            collectImports(imported, styles, preloads, visited);
        }
    }

    private String findEntryKey() {
        for (Map.Entry<String, Chunk> entry : chunks.entrySet()) {
            if (entry.getValue().isEntry && ENTRY_NAME.equals(entry.getValue().name)) {
                return entry.getKey();
            }
        }
        throw new IllegalStateException("The Vite manifest has no '" + ENTRY_NAME
                + "' entry. Is @mustache-react/vite-plugin listed in vite.config.ts?");
    }

    private String findComponentKey(String component) {
        for (String extension : COMPONENT_EXTENSIONS) {
            if (chunks.containsKey(component + extension)) {
                return component + extension;
            }
        }
        return null;
    }

    private static final class Chunk {
        final String file;
        final String name;
        final boolean isEntry;
        final List<String> imports;
        final List<String> css;

        Chunk(Map<?, ?> json) {
            Object file = json.get("file");
            if (!(file instanceof String)) {
                throw new IllegalArgumentException("Every Vite manifest chunk must have a 'file'");
            }
            this.file = (String) file;
            this.name = json.get("name") instanceof String ? (String) json.get("name") : null;
            this.isEntry = Boolean.TRUE.equals(json.get("isEntry"));
            this.imports = strings(json.get("imports"));
            this.css = strings(json.get("css"));
        }

        private static List<String> strings(Object value) {
            if (!(value instanceof List)) {
                return Collections.emptyList();
            }
            List<String> result = new ArrayList<>();
            for (Object item : (List<?>) value) {
                if (item instanceof String) {
                    result.add((String) item);
                }
            }
            return result;
        }
    }
}

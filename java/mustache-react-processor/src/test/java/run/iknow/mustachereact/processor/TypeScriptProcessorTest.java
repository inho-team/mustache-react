package run.iknow.mustachereact.processor;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import java.util.LinkedHashMap;
import java.util.Map;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class TypeScriptProcessorTest {

    @TempDir
    Path workDir;

    private static Map<String, String> sources(String... nameAndSource) {
        Map<String, String> map = new LinkedHashMap<>();
        for (int i = 0; i < nameAndSource.length; i += 2) {
            map.put(nameAndSource[i], nameAndSource[i + 1]);
        }
        return map;
    }

    private static final String CONTROLLER = "package app;\n"
            + "import run.iknow.mustachereact.spring.ReactPage;\n"
            + "public class OrderController {\n"
            + "  @ReactPage(\"orders/OrderList\") public OrderListResponse list() { return null; }\n"
            + "  @ReactPage(value = \"orders/Empty\", title = \"x\") public void empty() { }\n"
            + "}\n";

    private static final String RESPONSE = "package app;\n"
            + "import java.math.BigDecimal; import java.time.*; import java.util.*;\n"
            + "import com.fasterxml.jackson.annotation.*;\n"
            + "@JsonIgnoreProperties({\"internal\"})\n"
            + "public class OrderListResponse extends Paged<Order> {\n"
            + "  public int total;\n"
            + "  public static int CONSTANT;\n"
            + "  public List<Order> getOrders() { return null; }\n"
            + "  public Map<String, Integer> getCountByStatus() { return null; }\n"
            + "  public Optional<String> getNote() { return null; }\n"
            + "  public boolean isEmpty() { return false; }\n"
            + "  public Boolean isBoxed() { return null; }\n"
            + "  public String getURL() { return null; }\n"
            + "  public byte[] getChecksum() { return null; }\n"
            + "  public long[] getIds() { return null; }\n"
            + "  @JsonIgnore public String getSecret() { return null; }\n"
            + "  @JsonProperty(\"generated_at\") public Instant getGeneratedAt() { return null; }\n"
            + "  public String getInternal() { return null; }\n"
            + "  @Nullable public BigDecimal getDiscount() { return null; }\n"
            + "  public Object getExtra() { return null; }\n"
            + "  public String compute(int x) { return null; }\n"
            + "  protected String getHidden() { return null; }\n"
            + "  @java.lang.annotation.Retention(java.lang.annotation.RetentionPolicy.CLASS) @interface Nullable { }\n"
            + "}\n";

    private static final String PAGED = "package app;\n"
            + "public abstract class Paged<T> {\n"
            + "  public java.util.List<T> getContent() { return null; }\n"
            + "  public int getPage() { return 0; }\n"
            + "}\n";

    private static final String ORDER = "package app;\n"
            + "public class Order {\n"
            + "  public long getId() { return 0; }\n"
            + "  public java.time.LocalDate getOrderedAt() { return null; }\n"
            + "  public Status getStatus() { return null; }\n"
            + "  public Order getParent() { return null; }\n"
            + "  public enum Status { PAID, @com.fasterxml.jackson.annotation.JsonProperty(\"shipped\") SHIPPED, CANCELLED }\n"
            + "}\n";

    @Test
    void writesInterfacesForPagePropsAndReferencedClasses() throws Exception {
        Compilation result = Compilation.compile(workDir, sources(
                "app.OrderController", CONTROLLER, "app.OrderListResponse", RESPONSE, "app.Paged", PAGED,
                "app.Order", ORDER));

        assertThat(result.success).as(result.diagnostics).isTrue();
        assertThat(result.output).isEqualTo(""
                + "// Generated by mustache-react-processor from the Java classes. Do not edit.\n"
                + "// Rebuild the Java project to update it.\n\n"
                + "export interface Order {\n"
                + "  id: number;\n"
                + "  orderedAt: string;\n"
                + "  status: Status;\n"
                + "  parent: Order;\n"
                + "}\n\n"
                + "export interface OrderListResponse {\n"
                + "  orders: Order[];\n"
                + "  countByStatus: Record<string, number>;\n"
                + "  note: string | null;\n"
                + "  empty: boolean;\n"
                + "  boxed: boolean;\n"
                + "  url: string;\n"
                + "  checksum: string;\n"
                + "  ids: number[];\n"
                + "  generated_at: string;\n"
                + "  discount: number | null;\n"
                + "  extra: unknown;\n"
                + "  total: number;\n"
                + "  content: Order[];\n"
                + "  page: number;\n"
                + "}\n\n"
                + "export type Status = 'PAID' | 'shipped' | 'CANCELLED';\n\n"
                + "/** Props of each @ReactPage, by page name. */\n"
                + "export interface ReactPages {\n"
                + "  'orders/Empty': Record<string, never>;\n"
                + "  'orders/OrderList': OrderListResponse;\n"
                + "}\n\n"
                + "/** Props of a page, e.g. `PageProps<'orders/OrderList'>`. */\n"
                + "export type PageProps<P extends keyof ReactPages> = ReactPages[P];\n");
    }

    @Test
    void keepsGenericClassesGeneric() throws Exception {
        Compilation result = Compilation.compile(workDir, sources(
                "app.Controller", "package app;\n"
                        + "public class Controller {\n"
                        + "  @run.iknow.mustachereact.spring.ReactPage(\"p\") public Box<Item> page() { return null; }\n"
                        + "}\n",
                "app.Box", "package app; public class Box<T> { public T getValue() { return null; } "
                        + "public java.util.List<Box<T>> getChildren() { return null; } }",
                "app.Item", "package app; public class Item { public String getName() { return null; } }"));

        assertThat(result.output)
                .contains("export interface Box<T> {\n  value: T;\n  children: Box<T>[];\n}\n")
                .contains("export interface Item {\n  name: string;\n}\n")
                .contains("  'p': Box<Item>;\n");
    }

    @Test
    void writesReactTypeClassesAndLombokFields() throws Exception {
        Compilation result = Compilation.compile(workDir, sources(
                "lombok.Data", "package lombok; public @interface Data { }",
                "lombok.Getter", "package lombok; public @interface Getter { }",
                "app.ChartProps", "package app;\n"
                        + "@run.iknow.mustachereact.spring.ReactType @lombok.Data\n"
                        + "public class ChartProps { private String title; private int[] values; "
                        + "@com.fasterxml.jackson.annotation.JsonIgnore private String cache; private static int X; }",
                "app.Badge", "package app;\n"
                        + "@run.iknow.mustachereact.spring.ReactType\n"
                        + "public class Badge { @lombok.Getter private String label; private String hidden; }"));

        assertThat(result.output)
                .contains("export interface ChartProps {\n  title: string;\n  values: number[];\n}\n")
                .contains("export interface Badge {\n  label: string;\n}\n")
                .contains("export interface ReactPages {\n}\n");
    }

    @Test
    void disambiguatesClassesWithTheSameSimpleName() throws Exception {
        Compilation result = Compilation.compile(workDir, sources(
                "app.Controller", "package app;\n"
                        + "public class Controller {\n"
                        + "  @run.iknow.mustachereact.spring.ReactPage(\"p\") public Page page() { return null; }\n"
                        + "}\n",
                "app.Page", "package app; public class Page { public app.a.Item getA() { return null; } "
                        + "public app.b.Item getB() { return null; } }",
                "app.a.Item", "package app.a; public class Item { public int getX() { return 0; } }",
                "app.b.Item", "package app.b; public class Item { public String getY() { return null; } }"));

        assertThat(result.output)
                .contains("  a: Item;\n  b: app_b_Item;\n")
                .contains("export interface app_b_Item {\n  y: string;\n}\n");
    }

    @Test
    void readsRecordComponents() throws Exception {
        assumeTrue(Double.parseDouble(System.getProperty("java.specification.version")) >= 16, "records need Java 16+");

        Compilation result = Compilation.compile(workDir, sources(
                "app.Controller", "package app;\n"
                        + "public class Controller {\n"
                        + "  @run.iknow.mustachereact.spring.ReactPage(\"p\") public Summary page() { return null; }\n"
                        + "}\n",
                "app.Summary", "package app; public record Summary(String name, int total, "
                        + "@com.fasterxml.jackson.annotation.JsonIgnore String secret) { public String extra() { return null; } }"));

        assertThat(result.success).as(result.diagnostics).isTrue();
        assertThat(result.output).contains("export interface Summary {\n  name: string;\n  total: number;\n}\n");
    }

    @Test
    void prefersTheConcretePropsTypeOverAFormHandlersObject() throws Exception {
        Compilation result = Compilation.compile(workDir, sources(
                "app.FormController", "package app;\n"
                        + "import run.iknow.mustachereact.spring.ReactPage;\n"
                        + "public class FormController {\n"
                        + "  @ReactPage(\"f\") public Object create() { return \"redirect:/\"; }\n"
                        + "  @ReactPage(\"f\") public FormPage show() { return null; }\n"
                        + "  @ReactPage(\"g\") public FormPage show2() { return null; }\n"
                        + "  @ReactPage(\"g\") public String update() { return \"redirect:/\"; }\n"
                        + "}\n",
                "app.FormPage", "package app; public class FormPage { public String getName() { return null; } }"));

        assertThat(result.diagnostics).doesNotContain("different types");
        assertThat(result.output).contains("  'f': FormPage;\n  'g': FormPage;\n");
    }

    @Test
    void usesTheBodyTypeOfResponseEntity() throws Exception {
        Compilation result = Compilation.compile(workDir, sources(
                "org.springframework.http.ResponseEntity", "package org.springframework.http; public class ResponseEntity<T> { }",
                "app.Controller", "package app;\n"
                        + "import org.springframework.http.ResponseEntity;\n"
                        + "import run.iknow.mustachereact.spring.ReactPage;\n"
                        + "public class Controller {\n"
                        + "  @ReactPage(\"d\") public ResponseEntity<Detail> show() { return null; }\n"
                        + "  @ReactPage(\"w\") public ResponseEntity<?> any() { return null; }\n"
                        + "}\n",
                "app.Detail", "package app; public class Detail { public long getId() { return 0; } }"));

        assertThat(result.success).as(result.diagnostics).isTrue();
        assertThat(result.output).contains("  'd': Detail;\n").contains("  'w': unknown;\n")
                .contains("export interface Detail {\n  id: number;\n}\n");
    }

    @Test
    void leavesAnUnchangedFileAlone() throws Exception {
        Map<String, String> sources = sources("app.OrderController", CONTROLLER, "app.OrderListResponse", RESPONSE,
                "app.Paged", PAGED, "app.Order", ORDER);
        Compilation first = Compilation.compile(workDir, sources);
        FileTime old = FileTime.fromMillis(1_000_000L);
        Files.setLastModifiedTime(first.typesFile, old);

        Compilation.compile(workDir, sources);

        assertThat(Files.getLastModifiedTime(first.typesFile)).isEqualTo(old);
    }

    @Test
    void writesNothingWithoutAnnotations() throws Exception {
        Compilation result = Compilation.compile(workDir, sources("app.Plain", "package app; public class Plain { }"));

        assertThat(result.success).isTrue();
        assertThat(result.output).isNull();
    }
}
